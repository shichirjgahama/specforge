"""Custom hypothesis strategies required by the assignment.

These are not default hypothesis generators: each one understands the DSL and
the domain and produces structurally valid artifacts.

  st_dsl_program()       valid DSL programs with consistent references
  st_invalid_transition() forbidden transitions (unknown target state)
  st_cr()                change requests that edit 1 to 3 specification nodes
"""
from __future__ import annotations

from hypothesis import strategies as st

from .impact import ChangeRequest


ENTITY_POOL = ["Scooter", "Bike", "Board", "Moped"]
STATE_POOL = [
    ("free", "busy", "done"),
    ("ready", "moving", "parked"),
    ("open", "locked", "closed"),
]


@st.composite
def st_dsl_program(draw):
    entity = draw(st.sampled_from(ENTITY_POOL))
    var = entity[0].lower() + entity[1:]
    states = draw(st.sampled_from(STATE_POOL))
    enum_name = f"{entity}State"
    threshold = draw(st.integers(min_value=0, max_value=100))
    battery = draw(st.integers(min_value=0, max_value=100))
    s1, s2, s3 = states
    return f"""
spec Generated version 1;

const minBattery: Int = {threshold};

enum {enum_name} {{ {s1}, {s2}, {s3} }}

entity {entity} {{
  id: Identifier;
  state: State<{enum_name}> = {s1};
  battery: Int [0..100] = {battery};
}}

role Customer {{
  may reserve, rent, return;
}}

state {enum_name} {{
  initial {s1};
  {s1} -> {s2} : reserve when {var}.battery >= minBattery do {{
    {var}.state := {s2};
  }};
  {s2} -> {s3} : close do {{
    {var}.state := {s3};
  }};
  {s3} -> {s1} : reopen do {{
    {var}.state := {s1};
  }};
}}

rule RULE-1 {{
  when {var}.battery >= minBattery
  then {{
    {var}.state := {s2};
  }} else {{
    {var}.state := {s1};
  }}
  ensures {var}.battery >= 0;
}}

invariant INV-1 always {var}.battery >= 0 and {var}.battery <= 100
  message "battery stays in range";

scenario SC-1 {{
  given {var}.battery = {battery};
  expect {var}.battery >= 0;
}}
"""


GHOST_STATES = ["ghost", "void", "missing", "unknown", "phantom"]


@st.composite
def st_invalid_transition(draw):
    source = draw(st.sampled_from(["available", "reserved", "rented"]))
    target = draw(st.sampled_from(GHOST_STATES))
    event = draw(st.sampled_from(["jump", "teleport", "explode", "sneak"]))
    return {"source": source, "target": target, "event": event}


CONST_TEMPLATES = {
    "graceMinutes": ("const graceMinutes: Int = 10;", 0, 30),
    "minBattery": ("const minBattery: Int = 20;", 0, 100),
    "depositAmount": ("const depositAmount: Money = 3000;", 0, 6000),
    "damageClaimHours": ("const damageClaimHours: Int = 48;", 1, 96),
    "serviceMileage": ("const serviceMileage: Int = 500;", 50, 1000),
    "lateFeePerHour": ("const lateFeePerHour: Money = 500;", 0, 2000),
    "blacklistLateReturns": ("const blacklistLateReturns: Int = 3;", 0, 6),
    "reservationTtlMinutes": ("const reservationTtlMinutes: Int = 15;", 1, 60),
    "overdueBlockHours": ("const overdueBlockHours: Int = 24;", 1, 72),
}


@st.composite
def st_cr(draw):
    keys = draw(st.lists(st.sampled_from(sorted(CONST_TEMPLATES)),
                         min_size=1, max_size=3, unique=True))
    edits = []
    nodes = []
    for key in keys:
        find, low, high = CONST_TEMPLATES[key]
        value = draw(st.integers(min_value=low, max_value=high))
        prefix = find.rsplit("=", 1)[0] + "= "
        edits.append({"find": find, "replace": f"{prefix}{value};"})
        nodes.append(f"const:{key}")
    requirement_edits = []
    if draw(st.booleans()):
        requirement_edits.append({
            "id": draw(st.sampled_from(["R-005", "R-007", "R-011", "R-013"])),
            "criteria_add": ["generated by st_cr: threshold review"],
        })
    return ChangeRequest(
        id="CR-HYP", title="Generated change request", kind="rule_threshold",
        description="generated by st_cr()", spec_edits=edits,
        requirement_edits=requirement_edits, target_nodes=tuple(nodes),
    )
